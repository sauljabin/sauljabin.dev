#!/usr/bin/env python3
"""Stamps asset versions into index.html, then builds es/index.html from it.

    python3 tools/build.py

Asset URLs get ?v=<content hash>, so browsers never mix a new page with
cached old CSS, JS or images (GitHub Pages caches them for 10 minutes).

Translatable parts of index.html are marked with:
  data-i18n="key"          element text
  data-i18n-content="key"  content attribute (meta tags)
  data-i18n-label="key"    aria-label attribute
  data-page-url            href/content holding this page's URL
  data-lang="xx"           language switcher link
"""

import hashlib
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://sauljabin.dev"
MONTHS = "ene feb mar abr may jun jul ago sep oct nov dic".split()


def translate(source, texts):
    used = set()

    def text(key):
        if key not in texts:
            raise SystemExit(f"missing translation: {key}")
        used.add(key)
        return texts[key]

    def element(m):
        return m[1] + html.escape(text(m[3]), quote=False) + m[5]

    def attribute(name):
        def replace(m):
            tag, key = m[0], m[1]
            value = html.escape(text(key), quote=True)
            return re.sub(rf'{name}="[^"]*"', f'{name}="{value}"', tag, count=1)

        return replace

    def date(m):
        year, month = int(m[1]), int(m[2])
        return f'<time datetime="{m[1]}-{m[2]}">{MONTHS[month - 1]} {year}</time>'

    out = re.sub(r'(<(\w+)[^>]*\sdata-i18n="([^"]+)"[^>]*>)(.*?)(</\2>)', element, source, flags=re.S)
    out = re.sub(r'<[^>]*\sdata-i18n-content="([^"]+)"[^>]*>', lambda m: attribute("content")(m), out)
    out = re.sub(r'<[^>]*\sdata-i18n-label="([^"]+)"[^>]*>', lambda m: attribute("aria-label")(m), out)
    out = re.sub(r'<time datetime="(\d{4})-(\d{2})">[^<]*</time>', date, out)
    out = re.sub(r'(<[^>]*\sdata-page-url[^>]*>)', lambda m: m[1].replace(f'"{SITE}/"', f'"{SITE}/es/"'), out)
    out = out.replace('<html lang="en">', '<html lang="es">', 1)
    out = out.replace('<a class="logo" href="/"', '<a class="logo" href="/es/"', 1)
    out = out.replace(' data-lang="en" aria-current="page">', ' data-lang="en">', 1)
    out = out.replace(' data-lang="es">', ' data-lang="es" aria-current="page">', 1)
    out = out.replace(
        "<!doctype html>\n",
        "<!doctype html>\n<!-- generated by tools/build.py: edit index.html and tools/es.json instead -->\n",
        1,
    )

    unused = set(texts) - used
    if unused:
        raise SystemExit(f"unused translations: {', '.join(sorted(unused))}")
    return out


def stamp(source):
    def version(m):
        digest = hashlib.sha256((ROOT / m[1].lstrip("/")).read_bytes()).hexdigest()[:8]
        return f"{m[1]}?v={digest}"

    return re.sub(r"(/(?:assets/[\w./-]+|favicon\.svg|apple-touch-icon\.png))(?:\?v=\w+)?", version, source)


def main():
    source = stamp((ROOT / "index.html").read_text())
    (ROOT / "index.html").write_text(source)
    texts = json.loads((ROOT / "tools/es.json").read_text())
    (ROOT / "es").mkdir(exist_ok=True)
    (ROOT / "es/index.html").write_text(translate(source, texts))
    print("stamped index.html, wrote es/index.html")


if __name__ == "__main__":
    main()
